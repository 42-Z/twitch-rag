/**
 * Имя документа в том виде, в каком его показывают человеку и ассистенту.
 *
 * Отдельным модулем, потому что правило одно на две среды исполнения: его
 * применяют и Worker (перечень трансляций для ассистента), и страница (список
 * разобранного). Записи, разобранные до появления имён, своего имени не
 * имеют, и для них берётся прежний заголовок с площадки — это временное
 * состояние, а не правило: повторный разбор его снимает.
 */

export interface NamedStream {
  /** Имя документа, выработанное по содержанию эфира (FR-022). */
  docTitle?: string;
  /** Заголовок с площадки: запасной вариант для не перебранных записей. */
  title: string;
}

export function documentName(stream: NamedStream): string {
  return stream.docTitle !== undefined && stream.docTitle !== "" ? stream.docTitle : stream.title;
}
