/**
 * Имя документа в том виде, в каком его показывают человеку и ассистенту.
 *
 * Отдельным модулем, потому что правило одно на две среды исполнения: его
 * применяют и Worker (перечень трансляций для ассистента), и страница (список
 * разобранного).
 *
 * Заголовок с площадки сюда не подставляется (FR-027). Он кликбейт и о
 * содержании эфира не говорит, а показанный там, где ожидается имя, выдаёт
 * себя за имя документа. Запись, разобранная до появления имён, имени не
 * имеет — она и получает пустое, а что показать вместо него, решает место
 * показа: списку хватает даты рядом, очереди — самой даты как опознания.
 */

export interface NamedStream {
  /** Имя документа, выработанное по содержанию эфира (FR-022). */
  docTitle?: string;
}

export function documentName(stream: NamedStream): string {
  return stream.docTitle ?? "";
}

/**
 * Имя документа части эфира: к имени по содержанию дописывается, какая это
 * часть (FR-005). Без этого два документа за один день неразличимы.
 *
 * Метка ставится в коде, а не просится у модели: имя обязано её нести, а
 * полагаться на послушность ответа для этого нельзя. У неделёной записи имя
 * не меняется; уже помеченное — не помечается повторно.
 */
export function withPartLabel(name: string, part: { index: number; count: number } | undefined): string {
  if (part === undefined) return name;
  const label = `(часть ${part.index} из ${part.count})`;
  return name.endsWith(label) ? name : `${name} ${label}`;
}
